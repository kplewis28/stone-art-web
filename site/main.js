// loupe: a round lens that magnifies the photo under the cursor (tap on touch)
document.querySelectorAll(".loupe").forEach(fig => {
  const img = fig.querySelector("img");
  const lens = fig.querySelector(".lens");
  const zoom = parseFloat(fig.dataset.zoom) || 2.2;
  let tx = 0, ty = 0, x = 0, y = 0, raf = 0;

  function paint() {
    x += (tx - x) * (reduce ? 1 : 0.28);
    y += (ty - y) * (reduce ? 1 : 0.28);
    const r = img.getBoundingClientRect();
    const half = lens.offsetWidth / 2;
    lens.style.left = x + "px";
    lens.style.top = y + "px";
    lens.style.backgroundImage = `url("${img.currentSrc || img.src}")`;
    // object-fit: cover → map lens point to the rendered image box
    const nw = img.naturalWidth, nh = img.naturalHeight;
    const s = Math.max(r.width / nw, r.height / nh);
    const dw = nw * s, dh = nh * s, ox = (r.width - dw) / 2, oy = (r.height - dh) / 2;
    lens.style.backgroundSize = `${dw * zoom}px ${dh * zoom}px`;
    lens.style.backgroundPosition = `${-((x - ox) * zoom - half)}px ${-((y - oy) * zoom - half)}px`;
    if (Math.abs(tx - x) > 0.3 || Math.abs(ty - y) > 0.3) raf = requestAnimationFrame(paint); else raf = 0;
  }
  function aim(e, jump) {
    const r = img.getBoundingClientRect();
    tx = Math.min(Math.max(e.clientX - r.left, 0), r.width);
    ty = Math.min(Math.max(e.clientY - r.top, 0), r.height);
    if (jump) { x = tx; y = ty; }
    if (!raf) raf = requestAnimationFrame(paint);
  }
  function close() { fig.classList.remove("active", "on-touch"); }

  img.addEventListener("pointerenter", e => { if (e.pointerType === "mouse") { aim(e, true); fig.classList.add("active"); } });
  img.addEventListener("pointermove", e => {
    if (e.pointerType === "mouse" || fig.classList.contains("on-touch")) aim(e);
  });
  img.addEventListener("pointerleave", e => { if (e.pointerType === "mouse") close(); });
  img.addEventListener("pointerdown", e => {
    if (e.pointerType === "mouse") return;
    aim(e, !fig.classList.contains("active"));
    fig.classList.add("active", "on-touch");
  });
  document.addEventListener("pointerdown", e => {
    if (e.pointerType !== "mouse" && !fig.contains(e.target)) close();
  });
});

