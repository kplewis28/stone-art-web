const now = document.getElementById("ab-now");
const DUR = 6000;
let cur = 0, timer = 0, inView = false, hold = false;

function show(k, user) {
  cur = (k + tabs.length) % tabs.length;
  tabs.forEach((t, i) => {
    const on = i === cur;
    t.classList.toggle("on", on);
    t.classList.toggle("done", i < cur);
    t.setAttribute("aria-selected", on);
    t.tabIndex = on ? 0 : -1;
    panels[i].classList.toggle("on", on);
    panels[i].hidden = !on;
  });
  abUI.style.setProperty("--a", cur);
  now.textContent = String(cur + 1).padStart(2, "0");
  if (user) tabs[cur].focus({ preventScroll: true });
  restart();
}
function restart() {
  clearTimeout(timer);
  abUI.classList.remove("run");
  if (stopped || !inView) return;
  void abUI.offsetWidth; // restart the progress bar animation
  abUI.classList.add("run");
  abUI.style.setProperty("--dur", DUR + "ms");
  if (!hold) timer = setTimeout(() => show(cur + 1), DUR);
}
let stopped = reduce;
const pbtn = document.getElementById("ab-pause");
